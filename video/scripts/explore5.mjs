// Průzkum 3: dotaz na případ (bezstavový endpoint /ask), přepínač Předsedy / Pro mě.
import { chromium } from 'playwright';
const BASE = 'https://medteam.nervelabs.co.uk';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: process.env.LOCALAPPDATA + '/ms-playwright/chromium-1228/chrome-win64/chrome.exe' });
const p = await (await b.newContext({ viewport: { width: 1920, height: 1080 } })).newPage();
const shot = async (n) => { await p.waitForTimeout(1200); await p.screenshot({ path: `${out}/${n}.png` }); console.log('saved', n); };
await p.goto(BASE + '/login', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.getByRole('button', { name: 'Povolit vše' }).click({ timeout: 8000 }).catch(() => {});
await p.getByRole('button', { name: /Předseda komise/ }).click();
await p.waitForURL(/dashboard/, { timeout: 60000 });
await p.evaluate(() => { localStorage.setItem('theme', 'dark'); window.dispatchEvent(new Event('mdt-theme-change')); });
await p.goto(BASE + '/dashboard/cases/2', { waitUntil: 'domcontentloaded' }); await p.waitForTimeout(5000);
await p.getByRole('radio', { name: 'Předsedy' }).click().catch(() => p.getByText('Předsedy', { exact: true }).click());
await shot('h_chair');
await p.getByText(/Pro mě ·/).first().click(); await shot('h_me');
const sec = p.locator('button[aria-expanded]', { hasText: 'Zeptat se na případ' }).first();
if ((await sec.getAttribute('aria-expanded')) === 'false') await sec.click();
await p.evaluate(() => document.getElementById('dotaz')?.scrollIntoView({ block: 'center' }));
const input = p.getByPlaceholder(/Např. Kdy byla poslední dávka/);
await input.fill('Kdy byla poslední dávka bevacizumabu a jak to ovlivní termín resekce?');
await shot('h_ask_typed');
const t0 = Date.now();
await p.getByRole('button', { name: 'Zeptat se', exact: true }).click();
await p.waitForFunction(() => /Zdroj|P03-|\[/.test(document.getElementById('dotaz')?.innerText.split('Zeptat se')[2] ?? ''), null, { timeout: 120000 }).catch(() => {});
await p.waitForTimeout(3000);
console.log('answer after', Math.round((Date.now() - t0) / 1000), 's');
await p.evaluate(() => document.getElementById('dotaz')?.scrollIntoView({ block: 'start' }));
await shot('h_ask_answer');
console.log((await p.evaluate(() => document.getElementById('dotaz')?.innerText ?? '')).slice(0, 1500));
await b.close();
